#!/usr/bin/env python3
"""Derive the app's product assets from the approved SVGs, without network IO.

Requires Pillow (project dependency) and librsvg (Linux system library or
`brew install librsvg` on a Mac). --check compares every generated byte.
"""
from __future__ import annotations

import argparse
import ctypes as c
import ctypes.util
import io
from pathlib import Path
import xml.etree.ElementTree as ET

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
RES = Path("mobile/android/app/src/main/res")
INK = "#1C1C1A"
SVG = "{http://www.w3.org/2000/svg}"
DENSITIES = (("mdpi", 1), ("hdpi", 1.5), ("xhdpi", 2), ("xxhdpi", 3), ("xxxhdpi", 4))


class SvgRenderer:
    """Small binding to librsvg's public raster API (no PDF engine)."""

    def __init__(self) -> None:
        def library(name: str) -> c.CDLL:
            found = ctypes.util.find_library(name)
            if not found:
                raise RuntimeError(f"missing {name}; install librsvg before regenerating icons")
            return c.CDLL(found)

        self.rsvg = library("rsvg-2")
        self.pixbuf = library("gdk_pixbuf-2.0")
        self.objects = library("gobject-2.0")
        self.rsvg.rsvg_handle_new_from_data.argtypes = [c.c_char_p, c.c_size_t, c.c_void_p]
        self.rsvg.rsvg_handle_new_from_data.restype = c.c_void_p
        self.rsvg.rsvg_handle_get_pixbuf.argtypes = [c.c_void_p]
        self.rsvg.rsvg_handle_get_pixbuf.restype = c.c_void_p
        self.objects.g_object_unref.argtypes = [c.c_void_p]
        for name in ("width", "height", "rowstride", "n_channels"):
            fn = getattr(self.pixbuf, f"gdk_pixbuf_get_{name}")
            fn.argtypes = [c.c_void_p]
            fn.restype = c.c_int
        self.pixbuf.gdk_pixbuf_get_pixels.argtypes = [c.c_void_p]
        self.pixbuf.gdk_pixbuf_get_pixels.restype = c.c_void_p

    def png(self, source: str, width: int, height: int | None = None) -> bytes:
        tree = ET.fromstring(source)
        tree.set("width", str(width))
        tree.set("height", str(height or width))
        data = ET.tostring(tree)
        handle = self.rsvg.rsvg_handle_new_from_data(data, len(data), None)
        if not handle:
            raise RuntimeError("invalid source SVG")
        pixbuf = None
        try:
            pixbuf = self.rsvg.rsvg_handle_get_pixbuf(handle)
            if not pixbuf:
                raise RuntimeError("SVG rasterization failed")
            w, h, stride, channels = (getattr(self.pixbuf, f"gdk_pixbuf_get_{name}")(pixbuf)
                                      for name in ("width", "height", "rowstride", "n_channels"))
            mode = "RGBA" if channels == 4 else "RGB"
            # The final row need not include padding bytes.
            pixels = c.string_at(self.pixbuf.gdk_pixbuf_get_pixels(pixbuf), stride * (h - 1) + w * channels)
            image = Image.frombytes(mode, (w, h), pixels, "raw", mode, stride).convert("RGBA")
            output = io.BytesIO()
            image.save(output, format="PNG")
            return output.getvalue()
        finally:
            if pixbuf:
                self.objects.g_object_unref(pixbuf)
            self.objects.g_object_unref(handle)


def generate(root: Path) -> dict[Path, bytes]:
    renderer = SvgRenderer()
    symbol = ET.parse(root / "assets/brand/voiney-lab_symbol_white.svg").getroot()
    drawing = ET.tostring(symbol.find(f"{SVG}g"), encoding="unicode")
    paths = [item.attrib["d"] for item in symbol.iter(f"{SVG}path")]
    app = ET.parse(root / "assets/brand/voiney-lab_app-icon.svg").getroot()
    app.find(f"{SVG}rect").attrib.pop("rx")
    plate = ET.tostring(app, encoding="unicode")
    output: dict[Path, bytes] = {}

    def save(file: str | Path, content: str | bytes) -> None:
        output[Path(file)] = content.encode() if isinstance(content, str) else content

    def svg(body: str, width: int = 512, height: int | None = None) -> str:
        return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height or width}">{body}</svg>'

    def layer(width: int, height: int, size: float) -> str:
        return f'<g transform="translate({(width-size)/2} {(height-size)/2}) scale({size/24})">{drawing}</g>'

    def vector(viewport: int, size: int) -> str:
        lines = "\n".join(f'    <path android:pathData="{d}" android:fillColor="#00000000" android:strokeColor="#FFFFFFFF" android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round"/>' for d in paths)
        return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated from assets/brand/voiney-lab_symbol_white.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="{viewport}dp" android:height="{viewport}dp" android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">
  <group android:translateX="{(viewport-size)/2}" android:translateY="{(viewport-size)/2}" android:scaleX="{size/24}" android:scaleY="{size/24}">
{lines}
  </group>
</vector>
'''

    save("assets/brand/voiney-lab_maskable.svg", plate)
    maskable = renderer.png(plate, 512)
    for folder in ("assets/brand", "src/voiney_lab/static/icons", "web/public/brand"):
        save(f"{folder}/voiney-lab_maskable_512.png", maskable)
    for density, scale in DENSITIES:
        folder = RES / f"mipmap-{density}"
        save(folder / "ic_launcher.png", renderer.png(plate, int(48 * scale)))
        inner = "".join(ET.tostring(child, encoding="unicode") for child in app)
        rounded = svg(f'<defs><clipPath id="round"><circle cx="256" cy="256" r="256"/></clipPath></defs><g clip-path="url(#round)">{inner}</g>')
        save(folder / "ic_launcher_round.png", renderer.png(rounded, int(48 * scale)))
        save(folder / "ic_launcher_foreground.png", renderer.png(svg(layer(108, 108, 54), 108), int(108 * scale)))
    save(RES / "drawable-v24/ic_launcher_foreground.xml", vector(108, 54))
    save(RES / "drawable/ic_launcher_background.xml", f'<?xml version="1.0" encoding="utf-8"?>\n<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle"><solid android:color="{INK}"/></shape>\n')
    save(RES / "values/ic_launcher_background.xml", f'<?xml version="1.0" encoding="utf-8"?>\n<resources><color name="ic_launcher_background">{INK}</color></resources>\n')
    for name in ("ic_stat_voiney", "ic_stat_voiney_mic", "ic_stat_voiney_timer"):
        save(RES / f"drawable/{name}.xml", vector(24, 24))
    save(RES / "drawable/ic_splash_logo.xml", vector(288, 144))
    splashes = [("drawable", 480, 320)]
    for density, width, height in (("mdpi", 320, 480), ("hdpi", 480, 800), ("xhdpi", 720, 1280), ("xxhdpi", 960, 1600), ("xxxhdpi", 1280, 1920)):
        splashes.extend(((f"drawable-port-{density}", width, height), (f"drawable-land-{density}", height, width)))
    for folder, width, height in splashes:
        source = svg(f'<rect width="{width}" height="{height}" fill="{INK}"/>' + layer(width, height, min(width, height) * .4), width, height)
        save(RES / folder / "splash.png", renderer.png(source, width, height))
    return output


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare generated files without writing")
    args = parser.parse_args()
    files = generate(ROOT)
    for relative, data in files.items():
        file = ROOT / relative
        if args.check:
            if not file.is_file() or file.read_bytes() != data:
                raise SystemExit(f"asset differs: {relative}")
        else:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_bytes(data)
    print(f"{'checked' if args.check else 'generated'} {len(files)} product assets")


if __name__ == "__main__":
    main()
