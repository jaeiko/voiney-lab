#!/usr/bin/env python3
"""Build the STT1 reading list: 60 development sentences, even across fields, kinds and lengths.

The list is a case-id manifest (``scripts/sim/manifests/stt1_record_60.json``)
for the live tools and a sentence file (``sentences.js``) the recording page
beside this script reads. Only development cases are eligible -- the holdout
split is never read -- and the pick is outcome-blind, the LIVE3 sampler with
doubled quotas (biology 24, chemistry 12, materials 12, soil 12).

    python scripts/sim/record_kit/build.py --check   # the committed files match
    python scripts/sim/record_kit/build.py --write   # rewrite them (a deliberate change)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / 'src'))

from scripts.sim.diagnostic_manifest import development_pairs, family_group, length_bucket, select

KIT = Path(__file__).resolve().parent
MANIFEST = ROOT / 'scripts/sim/manifests/stt1_record_60.json'
SENTENCES = KIT / 'sentences.js'
MANIFEST_NAME = 'stt1-record-60'
SELECTION_SEED = 1031
FIELD_QUOTAS = {'biology': 24, 'chemistry': 12, 'materials': 12, 'soil': 12}
#: The recording conditions and microphones the page offers, as the file names carry them.
CONDITIONS = ('quiet', 'typing_after', 'fan')
MICROPHONES = ('device', 'lavalier')


def reading_list() -> list[dict]:
    pairs = development_pairs()
    chosen = select(pairs, seed=SELECTION_SEED, quotas=FIELD_QUOTAS, biology_per_protocol=4)
    by_code = {case.code: (protocol, case) for protocol, case in pairs}
    rows = []
    for number, code in enumerate(chosen, 1):
        protocol, case = by_code[code]
        rows.append({
            'id': code, 'number': number, 'text': ' '.join(case.text.split()),
            'protocol': protocol.code, 'field': protocol.field, 'family': case.family,
            'kind': family_group(case.family), 'length': length_bucket(case.text),
        })
    return rows


def documents(rows: list[dict]) -> tuple[str, str]:
    manifest = json.dumps({'schema': 1, 'name': MANIFEST_NAME, 'case_ids': [row['id'] for row in rows]},
                          ensure_ascii=False, indent=2) + '\n'
    payload = json.dumps({'schema': 1, 'kit': MANIFEST_NAME, 'conditions': list(CONDITIONS),
                          'microphones': list(MICROPHONES), 'sentences': rows}, ensure_ascii=False, indent=1)
    sentences = (
        '// Generated by scripts/sim/record_kit/build.py from the public SIM corpus '
        '(development split only). Do not edit by hand.\n'
        f'window.STT1_RECORD_KIT = {payload};\n'
    )
    return manifest, sentences


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--write', action='store_true')
    args = parser.parse_args(argv)
    rows = reading_list()
    manifest, sentences = documents(rows)
    if args.write:
        MANIFEST.write_text(manifest, encoding='utf-8')
        SENTENCES.write_text(sentences, encoding='utf-8')
        print(json.dumps({'written': [str(MANIFEST), str(SENTENCES)], 'sentences': len(rows)}))
        return 0
    matches = (
        MANIFEST.exists() and MANIFEST.read_text(encoding='utf-8') == manifest
        and SENTENCES.exists() and SENTENCES.read_text(encoding='utf-8') == sentences
    )
    print(json.dumps({'matches': bool(matches), 'sentences': len(rows)}))
    return 0 if matches else 1


if __name__ == '__main__':
    raise SystemExit(main())
